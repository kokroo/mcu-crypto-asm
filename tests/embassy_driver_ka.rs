//! Known-answer tests for the embassy-crypto driver glue (scratch validation only).
#![cfg(feature = "embassy-driver")]

use embassy_crypto::driver as drv;
use mcu_crypto_asm::embassy::McuCryptoAsmDriver;

#[test]
fn aes128_ecb_fips197() {
    use drv::Aes128Ecb;
    let ctx = <McuCryptoAsmDriver as Aes128Ecb>::init(&[
        0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e,
        0x0f,
    ]);
    let pt: [u8; 16] = [
        0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd, 0xee,
        0xff,
    ];
    let expected: [u8; 16] = [
        0x69, 0xc4, 0xe0, 0xd8, 0x6a, 0x7b, 0x04, 0x30, 0xd8, 0xcd, 0xb7, 0x80, 0x70, 0xb4, 0xc5,
        0x5a,
    ];
    let mut buf = pt;
    <McuCryptoAsmDriver as Aes128Ecb>::encrypt_blocks(&ctx, drv::InOutBuf::from(&mut buf[..]));
    assert_eq!(
        buf, expected,
        "AES-128 ECB encrypt != FIPS-197 known answer"
    );
    <McuCryptoAsmDriver as Aes128Ecb>::decrypt_blocks(&ctx, drv::InOutBuf::from(&mut buf[..]));
    assert_eq!(buf, pt, "AES-128 ECB decrypt roundtrip failed");
}


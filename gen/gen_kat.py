#!/usr/bin/env python3
"""Emit harness/src/kat.rs — known-answer vectors for the on-target tests.

The host oracle test proves the *portable* backend correct against num-bigint,
but it does so compiled for x86. These vectors pin the expected values
independently, so a target-specific miscompile cannot hide behind a
"both backends agree" differential result.
"""
import pathlib

# Random cases per curve, on top of the hand-picked carry edge cases.
N_RANDOM = 120

CURVES = {
    "P256": (8, 2**256 - 2**224 + 2**192 + 2**96 - 1),
    "P384": (12, 2**384 - 2**128 - 2**96 + 2**32 - 1),
}


def limbs(x, n):
    return [(x >> (32 * i)) & 0xFFFFFFFF for i in range(n)]


def arr(x, n):
    return "[" + ", ".join(f"0x{v:08x}" for v in limbs(x, n)) + "]"


out = [
    "//! GENERATED by `gen/gen_kat.py` — do not edit.",
    "//!",
    "//! Each entry is `(a, b, a*b mod p)` as plain integers, little-endian",
    "//! 32-bit limbs. The harness converts into Montgomery form, multiplies,",
    "//! converts back, and compares.",
    "#![allow(clippy::unreadable_literal)]",
    "",
]

for name, (n, p) in CURVES.items():
    # Values chosen to exercise carry propagation: extremes, near-p, and a
    # deterministic pseudo-random spread.
    cases = [
        (0, 0),
        (1, 1),
        (p - 1, p - 1),
        (p - 1, 1),
        (p - 1, 2),
        ((p - 1) // 2, (p + 1) // 2),
        (2**(32 * n - 1) % p, 2**(32 * n - 1) % p),
        ((1 << (32 * (n - 1))) - 1, (1 << (32 * (n - 1))) - 1),
    ]
    st = 0x243F6A8885A308D3
    for _ in range(N_RANDOM):
        v = []
        for _ in range(2):
            acc = 0
            for _ in range(n):
                st = (st * 6364136223846793005 + 1442695040888963407) % (1 << 64)
                acc = (acc << 32) | (st >> 32)
            v.append(acc % p)
        cases.append((v[0], v[1]))

    out.append(f"/// {name}: (a, b, a*b mod p)")
    out.append(
        f"pub const {name}_MUL: [([u32; {n}], [u32; {n}], [u32; {n}]); {len(cases)}] = ["
    )
    for a, b in cases:
        out.append(f"    ({arr(a,n)},")
        out.append(f"     {arr(b,n)},")
        out.append(f"     {arr(a*b % p,n)}),")
    out.append("];")
    out.append("")

dst = pathlib.Path(__file__).resolve().parent.parent / "harness" / "src" / "kat.rs"
dst.parent.mkdir(parents=True, exist_ok=True)
dst.write_text("\n".join(out))
print(f"wrote {dst}")
for name, (n, p) in CURVES.items():
    print(f"  {name}: 16 vectors, {n} limbs")


# ---- C header for the Xtensa harness ----------------------------------------
def carr(name, x, n):
    return (
        f"static const uint32_t {name}[{n}] = {{"
        + ", ".join(f"0x{v:08x}u" for v in limbs(x, n))
        + "};"
    )


ch = [
    "/* GENERATED by gen/gen_kat.py -- do not edit. */",
    "#ifndef NISTP_KAT_H",
    "#define NISTP_KAT_H",
    "#include <stdint.h>",
    "",
]
for name, (n, p_) in CURVES.items():
    R = (1 << (32 * n)) % p_
    R2 = (R * R) % p_
    ch.append(f"#define {name}_N {n}")
    ch.append(carr(f"{name}_P", p_, n))
    ch.append(carr(f"{name}_R2", R2, n))
    ch.append(carr(f"{name}_ONE", 1, n))

    cases = [
        (0, 0), (1, 1), (p_ - 1, p_ - 1), (p_ - 1, 1), (p_ - 1, 2),
        ((p_ - 1) // 2, (p_ + 1) // 2),
        (2 ** (32 * n - 1) % p_, 2 ** (32 * n - 1) % p_),
        ((1 << (32 * (n - 1))) - 1, (1 << (32 * (n - 1))) - 1),
    ]
    st = 0x243F6A8885A308D3
    for _ in range(N_RANDOM):
        v = []
        for _ in range(2):
            acc = 0
            for _ in range(n):
                st = (st * 6364136223846793005 + 1442695040888963407) % (1 << 64)
                acc = (acc << 32) | (st >> 32)
            v.append(acc % p_)
        cases.append((v[0], v[1]))

    ch.append(f"#define {name}_NCASES {len(cases)}")
    ch.append(f"static const uint32_t {name}_CASES[{len(cases)}][3][{n}] = {{")
    for a, b in cases:
        def row(x):
            return "{" + ", ".join(f"0x{v:08x}u" for v in limbs(x, n)) + "}"
        ch.append(f"  {{{row(a)}, {row(b)}, {row(a*b % p_)}}},")
    ch.append("};")
    ch.append("")
ch.append("#endif")

cdst = pathlib.Path(__file__).resolve().parent.parent / "harness-xtensa" / "kat.h"
cdst.parent.mkdir(parents=True, exist_ok=True)
cdst.write_text("\n".join(ch))
print(f"wrote {cdst}")

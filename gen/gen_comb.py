#!/usr/bin/env python3
"""Emit src/comb_tables.rs — fixed-base comb tables for the generator point.

`k*G` dominates public-key derivation and ECDSA signing, and G is known at
compile time, so the multiples can be precomputed instead of built at runtime.

The scalar is split into 4 equal blocks of `d = bits/4`. Entry `j` of the table
is the sum of `2^(b*d) * G` over the bits `b` set in `j`, so one table lookup
plus one addition consumes one bit from *every* block at once:

    acc = 0
    for i in (0..d).rev():
        acc = 2*acc
        digit = bit i of block0 | bit i of block1 << 1 | ...
        acc += T[digit]

That is `d` doublings and `d` additions -- 128 point operations for P-256
against 334 for the runtime 4-bit window, and 192 against 494 for P-384.

Entries are stored **affine and in Montgomery form**, so they can be used
directly without conversion. 16 entries x 2 coordinates: 1 KiB of flash for
P-256, 1.5 KiB for P-384.
"""
import pathlib

CURVES = {
    "P256": dict(
        n=8,
        p=2**256 - 2**224 + 2**192 + 2**96 - 1,
        gx=0x6B17D1F2E12C4247F8BCE6E563A440F277037D812DEB33A0F4A13945D898C296,
        gy=0x4FE342E2FE1A7F9B8EE7EB4A7C0F9E162BCE33576B315ECECBB6406837BF51F5,
    ),
    "P384": dict(
        n=12,
        p=2**384 - 2**128 - 2**96 + 2**32 - 1,
        gx=0xAA87CA22BE8B05378EB1C71EF320AD746E1D3B628BA79B9859F741E082542A385502F25DBF55296C3A545E3872760AB7,
        gy=0x3617DE4A96262C6F5D9E98BF9292DC29F8F41DBD289A147CE9DA3113B5F0B8C00A60B1CE1D7E819D7A431D7C90EA0E5F,
    ),
}

BLOCKS = 4      # blocks per table -> 16 entries each
NTABLES = 4     # number of tables

# Total point operations are d*(1 + NTABLES) with d = bits/(BLOCKS*NTABLES),
# while the total masked-scan cost is INDEPENDENT of NTABLES (more tables,
# proportionally fewer iterations). So more tables is a strict speed win until
# the additions dominate:
#   T=1 -> 128 ops (P-256)   T=2 -> 96   T=4 -> 80   T=8 -> 72
# T=4 is the knee; beyond it flash doubles for a few percent.


def add(P, Q, p):
    """Affine addition on y^2 = x^3 - 3x + b. None is the identity."""
    a = -3 % p
    if P is None:
        return Q
    if Q is None:
        return P
    x1, y1 = P
    x2, y2 = Q
    if x1 == x2 and (y1 + y2) % p == 0:
        return None
    if P == Q:
        lam = (3 * x1 * x1 + a) * pow(2 * y1, -1, p) % p
    else:
        lam = (y2 - y1) * pow(x2 - x1, -1, p) % p
    x3 = (lam * lam - x1 - x2) % p
    return (x3, (lam * (x1 - x3) - y1) % p)


def mul(k, P, p):
    R = None
    for bit in bin(k)[2:] if k else "0":
        R = add(R, R, p)
        if bit == "1":
            R = add(R, P, p)
    return R


def limbs(x, n):
    return [(x >> (32 * i)) & 0xFFFFFFFF for i in range(n)]


def arr(x, n):
    return "[" + ", ".join(f"0x{v:08x}" for v in limbs(x, n)) + "]"


out = [
    "//! Fixed-base comb tables. GENERATED by `gen/gen_comb.py` — do not edit.",
    "//!",
    "//! `COMB[j]` is `(x, y)` affine in **Montgomery form** for",
    "//! `sum over bits b set in j of 2^(b*D) * G`.",
    "//! `COMB[0]` is the identity, stored as `(0, 1)` — NOT `(0, 0)` — because",
    "//! the caller pairs it with `Z = 0` and the projective identity is",
    "//! `(0 : 1 : 0)`. All-zero coordinates are not a point at all, and the",
    "//! complete addition formulas do not rescue them.",
    "#![allow(clippy::unreadable_literal)]",
    "",
]

for name, c in CURVES.items():
    n, p = c["n"], c["p"]
    R = (1 << (32 * n)) % p
    bits = 32 * n
    G = (c["gx"], c["gy"])

    d = bits // (BLOCKS * NTABLES)
    entries = []
    for t in range(NTABLES):
        for j in range(1 << BLOCKS):
            acc = None
            for b in range(BLOCKS):
                if j & (1 << b):
                    shift = (t * BLOCKS + b) * d
                    acc = add(acc, mul(1 << shift, G, p), p)
            entries.append(acc)

    out.append(f"/// {name}: comb iterations (bits per block).")
    out.append(f"pub const {name}_COMB_D: usize = {d};")
    out.append(f"/// {name}: number of 16-entry tables.")
    out.append(f"pub const {name}_COMB_T: usize = {NTABLES};")
    out.append(f"/// {name} comb tables, affine Montgomery form, {NTABLES} x 16 entries.")
    out.append(
        f"pub const {name}_COMB: [([u32; {n}], [u32; {n}]); {NTABLES * (1 << BLOCKS)}] = ["
    )
    for jj, e in enumerate(entries):
        j = jj % (1 << BLOCKS)
        if e is None:
            # Identity: (0 : 1 : 0). y must be Montgomery 1, not 0.
            out.append(f"    ({arr(0,n)},")
            out.append(f"     {arr(R % p, n)}),   // t={jj >> BLOCKS} j={j}: identity")
        else:
            out.append(f"    ({arr(e[0]*R % p, n)},")
            out.append(f"     {arr(e[1]*R % p, n)}),   // t={jj >> BLOCKS} j={j}")
    out.append("];")
    out.append("")

dst = pathlib.Path(__file__).resolve().parent.parent / "src" / "comb_tables.rs"
dst.write_text("\n".join(out))
print(f"wrote {dst}")
for name, c in CURVES.items():
    n = c["n"]
    d = 32 * n // (BLOCKS * NTABLES)
    ent = NTABLES * (1 << BLOCKS)
    print(f"  {name}: D={d}, {NTABLES}x16={ent} entries, {ent*2*n*4} bytes, "
          f"{d} doublings + {d*NTABLES} additions = {d*(1+NTABLES)} ops per k*G")

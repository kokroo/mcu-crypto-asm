#!/usr/bin/env python3
"""Emit asm/cortex_m4.S — unrolled FIOS Montgomery multiply using UMAAL and VFP,
plus constant-time assembly add_mod and sub_mod.

Generated rather than hand-written: P-256 needs ~120 UMAAL and P-384 ~264.
Hand-maintaining that is how you get a silent carry bug.

The modular multiplication routine is built on UMAAL:
    UMAAL RdLo, RdHi, Rn, Rm   ->   RdHi:RdLo = Rn*Rm + RdHi + RdLo
which is exactly the CIOS/FIOS inner step `(C, t[j]) = t[j] + a[j]*b[i] + C`,
single cycle on Cortex-M4, and cannot overflow 64 bits.

n0' == 1 for both NIST primes (p ≡ -1 mod 2^32), so the reduction multiplier
is just `m = t[0]` — no multiply at all.

To eliminate RAM bus contention between instruction fetch and data loads/stores
on Cortex-M4 (where running from RAM causes bus arbitration stalls), operand `a`
and the accumulator `t` are kept entirely in VFP registers (s0..s31) via single-cycle
internal core moves (`vmov`), eliminating all stack traffic during the loops.
"""
import pathlib

MODULI = {
    8: 2**256 - 2**224 + 2**192 + 2**96 - 1,
    12: 2**384 - 2**128 - 2**96 + 2**32 - 1,
}


def limbs(x, n):
    return [(x >> (32 * i)) & 0xFFFFFFFF for i in range(n)]


def const_regs(p_limbs):
    """Map each distinct modulus limb value to a register holding it.

    r11 always holds 0 (it is already needed for carry-only adds). The other
    distinct values get r12 and lr, both free here: r12 is caller-saved, and
    lr is dead because the routine returns via `pop {..., pc}`.
    """
    distinct = sorted(set(p_limbs))
    mapping, setup, spare = {}, [], ["r12", "lr"]
    for v in distinct:
        if v == 0:
            mapping[v] = "r11"
            continue
        reg = spare.pop(0)
        mapping[v] = reg
        if v == 0xFFFFFFFF:
            setup.append(f"	mvn	{reg}, #0			@ 0xffffffff")
        elif v == 0xFFFFFFFE:
            setup.append(f"	mvn	{reg}, #1			@ 0xfffffffe")
        elif v < 256:
            setup.append(f"	mov	{reg}, #{v}")
        else:
            setup.append(f"	movw	{reg}, #{v & 0xFFFF}")
            setup.append(f"	movt	{reg}, #{v >> 16}")
    return mapping, setup


HEADER = r"""@ GENERATED by gen/gen_asm_cortex_m4.py -- do not edit.
@
@ Constant-time Montgomery multiplication and modular add/sub for NIST P-256 / P-384.
@ Requires ARMv7-M (Cortex-M3/M4/M7) or ARMv7-A for UMAAL. Thumb-2; included via global_asm!.

	.syntax unified
	.thumb
	.arch armv7e-m
	.fpu fpv4-sp-d16
	.text
"""


def emit_mul(n):
    """Fully-unrolled FIOS Montgomery multiply for `n` limbs using VFP registers.

    Operands and accumulator are kept in VFP registers to eliminate RAM loads and
    stores during the loop, eliminating bus arbitration stalls on Cortex-M4.
    """
    assert n % 2 == 0
    L = []
    e = L.append
    name = f"nistp_mul_mont_{n}"
    pl = limbs(MODULI[n], n)
    creg, csetup = const_regs(pl)

    if n == 8:
        d_callee = "{d8}"
    elif n == 12:
        d_callee = "{d8-d12}"
    else:
        raise ValueError(f"unsupported n={n}")

    out_s = f"s{2*n + 1}"

    e("")
    e(f"@ void {name}(uint32_t out[{n}], const uint32_t a[{n}],")
    e(f"@                const uint32_t b[{n}], const uint32_t p[{n}]);")
    e(f"@ out = a * b * R^-1 mod p,  R = 2^{32*n}.  FIOS with VFP registers.")
    e(f"	.globl	{name}")
    e(f"	.p2align 2")
    e(f"	.thumb_func")
    e(f"	.type	{name}, %function")
    e(f"{name}:")
    e(f"	push	{{r4-r11, lr}}")
    e(f"	sub	sp, sp, #4")
    e(f"	vpush	{d_callee}")
    e(f"	vmov	{out_s}, r0		@ park `out` in VFP")
    e(f"	vldm	r1, {{s0-s{n-1}}}	@ load operand `a` once")
    e(f"	mov	r11, #0			@ permanent zero")
    for line in csetup:
        e(line)

    for i in range(n):
        e(f"	@ ---- i = {i} ----")
        e(f"	ldr	r5, [r2, #{i*4}]		@ b[{i}]")
        # j = 0
        if i == 0:
            e(f"	vmov	r8, s0")
            e(f"	mov	r6, #0			@ C1 = 0")
            e(f"	mov	r7, #0")
            e(f"	umaal	r7, r6, r8, r5		@ S = a[0]*b[0]")
            e(f"	mov	r9, r7			@ m = S   (n0' == 1)")
            e(f"	mov	r0, #0			@ C2 = 0")
            e(f"	umaal	r7, r0, r9, {creg[pl[0]]}		@ low word cancels")
        else:
            e(f"	vmov	r8, s0")
            e(f"	vmov	r7, s{n}")
            e(f"	mov	r6, #0			@ C1 = 0")
            e(f"	umaal	r7, r6, r8, r5		@ S = t[0] + a[0]*b[i]")
            e(f"	mov	r9, r7			@ m = S   (n0' == 1)")
            e(f"	mov	r0, #0			@ C2 = 0")
            e(f"	umaal	r7, r0, r9, {creg[pl[0]]}		@ low word cancels")

        # j = 1
        if i == 0:
            e(f"	vmov	r8, s1")
            e(f"	mov	r7, #0")
            e(f"	umaal	r7, r6, r8, r5")
            e(f"	umaal	r7, r0, r9, {creg[pl[1]]}")
            e(f"	vmov	s{n}, r7		@ t[0] = S")
        else:
            e(f"	vmov	r8, s1")
            e(f"	vmov	r7, s{n+1}")
            e(f"	umaal	r7, r6, r8, r5")
            e(f"	umaal	r7, r0, r9, {creg[pl[1]]}")
            e(f"	vmov	s{n}, r7		@ t[0] = S")

        # j = 2 .. n-1
        for j in range(2, n, 2):
            e(f"	vmov	r8, r10, s{j}, s{j+1}")
            if i == 0:
                e(f"	mov	r7, #0")
                e(f"	mov	r3, #0")
            else:
                e(f"	vmov	r7, r3, s{n+j}, s{n+j+1}")
            e(f"	umaal	r7, r6, r8, r5")
            e(f"	umaal	r3, r6, r10, r5")
            e(f"	umaal	r7, r0, r9, {creg[pl[j]]}")
            e(f"	umaal	r3, r0, r9, {creg[pl[j+1]]}")
            e(f"	vmov	s{n+j-1}, s{n+j}, r7, r3")

        # tail: fold carries
        if i == 0:
            e(f"	adds	r7, r6, r0")
            e(f"	adc.w	r8, r11, r11")
            e(f"	vmov	s{2*n-1}, s{2*n}, r7, r8")
        else:
            e(f"	vmov	r7, s{2*n}")
            e(f"	adds	r7, r7, r6")
            e(f"	adc.w	r8, r11, r11")
            e(f"	adds	r7, r7, r0")
            e(f"	adc.w	r10, r11, r11")
            e(f"	add	r8, r8, r10")
            e(f"	vmov	s{2*n-1}, s{2*n}, r7, r8")

    # ---- conditional subtraction ----
    e(f"	vmov	r0, {out_s}		@ recover `out`")
    e(f"	vmov	r7, s{n}")
    e(f"	subs	r7, r7, {creg[pl[0]]}")
    for j in range(1, n):
        e(f"	vmov	r7, s{n+j}")
        e(f"	sbcs	r7, r7, {creg[pl[j]]}")
    e(f"	vmov	r7, s{2*n}")
    e(f"	sbcs	r7, r7, r11")
    e(f"	sbc	r10, r10, r10		@ -1 if borrow, 0 if no borrow")
    e(f"	mvn	r10, r10		@ 0 if borrow, all-ones if no borrow")
    e(f"	and	r12, r12, r10")
    e(f"	and	lr, lr, r10")

    for j in range(0, n, 2):
        e(f"	vmov	r7, r8, s{n+j}, s{n+j+1}")
        if j == 0:
            e(f"	subs	r7, r7, {creg[pl[0]]}")
            e(f"	sbcs	r8, r8, {creg[pl[1]]}")
        else:
            e(f"	sbcs	r7, r7, {creg[pl[j]]}")
            e(f"	sbcs	r8, r8, {creg[pl[j+1]]}")
        e(f"	strd	r7, r8, [r0, #{j*4}]")

    e(f"	vpop	{d_callee}")
    e(f"	add	sp, sp, #4")
    e(f"	pop	{{r4-r11, pc}}")
    e(f"	.size	{name}, .-{name}")
    return "\n".join(L)


def emit_add_mod(n):
    assert n % 2 == 0
    L = []
    e = L.append
    name = f"nistp_add_mod_{n}"
    pl = limbs(MODULI[n], n)
    creg, csetup = const_regs(pl)

    e("")
    e(f"@ void {name}(uint32_t out[{n}], const uint32_t a[{n}],")
    e(f"@                const uint32_t b[{n}], const uint32_t p[{n}]);")
    e(f"@ out = a + b mod p.")
    e(f"	.globl	{name}")
    e(f"	.p2align 2")
    e(f"	.thumb_func")
    e(f"	.type	{name}, %function")
    e(f"{name}:")
    e(f"	push	{{r4-r11, lr}}")
    e(f"	mov	r11, #0			@ permanent zero")
    for line in csetup:
        e(line)

    # Pass 1: s = a + b
    for j in range(0, n, 2):
        e(f"	ldrd	r4, r5, [r1, #{j*4}]")
        e(f"	ldrd	r6, r7, [r2, #{j*4}]")
        if j == 0:
            e(f"	adds	r4, r4, r6")
            e(f"	adcs	r5, r5, r7")
        else:
            e(f"	adcs	r4, r4, r6")
            e(f"	adcs	r5, r5, r7")
        e(f"	vmov	s{j}, s{j+1}, r4, r5")
    e(f"	adc	r3, r11, r11		@ carry-out")

    # Pass 2: borrow = s - p
    for j in range(0, n, 2):
        e(f"	vmov	r4, r5, s{j}, s{j+1}")
        if j == 0:
            e(f"	subs	r4, r4, {creg[pl[0]]}")
            e(f"	sbcs	r5, r5, {creg[pl[1]]}")
        else:
            e(f"	sbcs	r4, r4, {creg[pl[j]]}")
            e(f"	sbcs	r5, r5, {creg[pl[j+1]]}")
    e(f"	sbcs	r3, r3, r11")
    e(f"	sbc	r10, r10, r10		@ -1 if s < p, 0 if s >= p")
    e(f"	mvn	r10, r10		@ 0 if s < p, all-ones if s >= p")
    e(f"	and	r12, r12, r10")
    e(f"	and	lr, lr, r10")

    # Pass 3: out = s - (p & mask)
    for j in range(0, n, 2):
        e(f"	vmov	r4, r5, s{j}, s{j+1}")
        if j == 0:
            e(f"	subs	r4, r4, {creg[pl[0]]}")
            e(f"	sbcs	r5, r5, {creg[pl[1]]}")
        else:
            e(f"	sbcs	r4, r4, {creg[pl[j]]}")
            e(f"	sbcs	r5, r5, {creg[pl[j+1]]}")
        e(f"	strd	r4, r5, [r0, #{j*4}]")

    e(f"	pop	{{r4-r11, pc}}")
    e(f"	.size	{name}, .-{name}")
    return "\n".join(L)


def emit_sub_mod(n):
    assert n % 2 == 0
    L = []
    e = L.append
    name = f"nistp_sub_mod_{n}"
    pl = limbs(MODULI[n], n)
    creg, csetup = const_regs(pl)

    e("")
    e(f"@ void {name}(uint32_t out[{n}], const uint32_t a[{n}],")
    e(f"@                const uint32_t b[{n}], const uint32_t p[{n}]);")
    e(f"@ out = a - b mod p.")
    e(f"	.globl	{name}")
    e(f"	.p2align 2")
    e(f"	.thumb_func")
    e(f"	.type	{name}, %function")
    e(f"{name}:")
    e(f"	push	{{r4-r11, lr}}")
    e(f"	mov	r11, #0			@ permanent zero")
    for line in csetup:
        e(line)

    # Pass 1: d = a - b
    for j in range(0, n, 2):
        e(f"	ldrd	r4, r5, [r1, #{j*4}]")
        e(f"	ldrd	r6, r7, [r2, #{j*4}]")
        if j == 0:
            e(f"	subs	r4, r4, r6")
            e(f"	sbcs	r5, r5, r7")
        else:
            e(f"	sbcs	r4, r4, r6")
            e(f"	sbcs	r5, r5, r7")
        e(f"	vmov	s{j}, s{j+1}, r4, r5")
    e(f"	sbc	r10, r10, r10		@ -1 if a < b, 0 if a >= b")
    e(f"	and	r12, r12, r10")
    e(f"	and	lr, lr, r10")

    # Pass 2: out = d + (p & mask)
    for j in range(0, n, 2):
        e(f"	vmov	r4, r5, s{j}, s{j+1}")
        if j == 0:
            e(f"	adds	r4, r4, {creg[pl[0]]}")
            e(f"	adcs	r5, r5, {creg[pl[1]]}")
        else:
            e(f"	adcs	r4, r4, {creg[pl[j]]}")
            e(f"	adcs	r5, r5, {creg[pl[j+1]]}")
        e(f"	strd	r4, r5, [r0, #{j*4}]")

    e(f"	pop	{{r4-r11, pc}}")
    e(f"	.size	{name}, .-{name}")
    return "\n".join(L)


def emit_mul_12():
    """Circular-buffer Montgomery multiplication for NIST P-384 on Cortex-M4.

    Exploits the special NIST P-384 prime structure:
        p = 2^384 - 2^128 - 2^96 + 2^32 - 1
    Montgomery reduction requires ZERO multiplications:
        M*p = (M << 384) - (M << 128) - (M << 96) + (M << 32) - M
    allowing the reduction multipliers m[0..11] to be computed with simple addition/subtraction
    directly during the multiplication outer loop.
    Accumulators and operands stay entirely in VFP registers s0..s23 in a circular buffer,
    eliminating AHB bus contention and shifting overhead.
    """
    L = []
    e = L.append

    e("")
    e("@ void nistp_mul_mont_12(uint32_t out[12], const uint32_t a[12],")
    e("@                         const uint32_t b[12], const uint32_t p[12]);")
    e("@ Circular-buffer Montgomery multiplication for NIST P-384 on Cortex-M4.")
    e("	.globl	nistp_mul_mont_12")
    e("	.p2align 2")
    e("	.thumb_func")
    e("	.type	nistp_mul_mont_12, %function")
    e("nistp_mul_mont_12:")
    e("	push	{r4-r11, lr}")
    e("	sub	sp, sp, #4			@ align sp to 8 bytes for vpush")
    e("	vpush	{d8-d11}")
    e("	sub	sp, sp, #56			@ 48 bytes for m[0..11], 4 for `out`, 4 pad")
    e("	str	r0, [sp, #48]			@ park `out` on stack")
    e("	vldm	r1, {d0-d5}			@ load all 12 words of `a` into s0..s11")
    e("	mov	r11, #0				@ permanent zero")
    e("	mov	r4, #0				@ initial carry = 0")

    # Initialize s12..s23 to 0 (T_circ)
    for k in range(0, 12, 2):
        e(f"	vmov	s{12+k}, s{13+k}, r11, r11")

    # Register mapping for rotating window of recent m values:
    # W_regs[0] = r0, W_regs[1] = r1, W_regs[2] = r3, W_regs[3] = r12
    W_regs = ["r0", "r1", "r3", "r12"]
    e("	mov	r0, #0				@ m window init")
    e("	mov	r1, #0")
    e("	mov	r3, #0")
    e("	mov	r12, #0")

    for i in range(12):
        e(f"	@ ==================== OUTER LOOP i = {i} ====================")
        e(f"	ldr	r5, [r2, #{i*4}]		@ b[{i}]")

        col_0 = i
        col_1 = (i + 1) % 12
        tgt = W_regs[i % 4]

        e(f"	vmov	r8, r10, s0, s1")
        if i < 11:
            e(f"	vmov	r7, lr, s{12+col_0}, s{12+col_1}")
        else:
            e(f"	vmov	r7, s{12+col_0}")
            e(f"	vmov	lr, s{12+col_1}")
        e(f"	mov	r6, #0				@ mul carry = 0")
        e(f"	umaal	r7, r6, r8, r5			@ t0 = T_circ[{col_0}] + a[0]*b[{i}]")
        e(f"	umaal	lr, r6, r10, r5			@ t1 = T_circ[{col_1}] + a[1]*b[{i}]")
        e(f"	vmov	s{12+col_1}, lr")

        # Compute m[i] from r7:
        # val = r7 + m[i-1] - m[i-3] - m[i-4] - carry
        if i >= 1:
            w1 = W_regs[(i - 1) % 4]
            e(f"	adds	r7, r7, {w1}			@ + m[{i-1}]")
            e(f"	adc.w	r8, r11, r11")
        else:
            e(f"	mov	r8, #0")

        if i >= 3:
            w3 = W_regs[(i - 3) % 4]
            e(f"	subs	r7, r7, {w3}			@ - m[{i-3}]")
            e(f"	sbc	r8, r8, r11")

        if i >= 4:
            w4 = W_regs[(i - 4) % 4]
            e(f"	subs	r7, r7, {w4}			@ - m[{i-4}]")
            e(f"	sbc	r8, r8, r11")

        # Subtract carry (in r4):
        e(f"	subs	r7, r7, r4")
        e(f"	sbc	r8, r8, r4, asr #31")
        e(f"	subs	r4, r11, r8			@ new carry = -r8")
        e(f"	str	r7, [sp, #{i*4}]		@ store m[{i}] for final reduction")
        e(f"	mov	{tgt}, r7			@ save m[{i}] into {tgt}")

        # Inner loop: j = 2 .. 11 in pairs:
        for j in range(2, 12, 2):
            c0 = (i + j) % 12
            c1 = (i + j + 1) % 12
            e(f"	vmov	r8, r10, s{j}, s{j+1}")
            if c0 + 1 == c1:
                e(f"	vmov	r7, lr, s{12+c0}, s{12+c1}")
                e(f"	umaal	r7, r6, r8, r5")
                e(f"	umaal	lr, r6, r10, r5")
                e(f"	vmov	s{12+c0}, s{12+c1}, r7, lr")
            else:
                e(f"	vmov	r7, s{12+c0}")
                e(f"	vmov	lr, s{12+c1}")
                e(f"	umaal	r7, r6, r8, r5")
                e(f"	umaal	lr, r6, r10, r5")
                e(f"	vmov	s{12+c0}, r7")
                e(f"	vmov	s{12+c1}, lr")

        # Tail carry goes into T_circ[i] (which becomes T[i+12]!):
        e(f"	vmov	s{12+col_0}, r6")

    e("")
    e("	@ ==================== FINAL REDUCTION ====================")
    # At this point:
    # s12..s23 holds T[12..23] (T_hi) in order s12..s23!
    # m8 is in r0, m9 is in r1, m10 is in r3, m11 is in r12!
    # carry is in r4!

    # 1. Compute D = (M >> 288) + (M >> 256) + carry - m[11]
    # d0 in r8, d1 in r9, d2 in r10, d3 in lr, d4 in r4
    e("	adds	r8, r0, r1			@ m8 + m9")
    e("	adc.w	r2, r11, r11			@ r2 = carry out")
    e("	adds	r8, r8, r4			@ + carry")
    e("	adcs	r2, r2, r4, asr #31")
    e("	subs	r8, r8, r12			@ - m11 -> r8 is d0")
    e("	sbc	r2, r2, r11			@ r2 = c0")

    # Step 1: val1 = m9 + m10 + c0
    e("	adds	r9, r1, r3			@ m9 + m10")
    e("	adc.w	r5, r11, r11")
    e("	adds	r9, r9, r2			@ + c0 -> r9 is d1")
    e("	adcs	r5, r5, r2, asr #31		@ r5 = c1")

    # Step 2: val2 = m10 + m11 + c1
    e("	adds	r10, r3, r12			@ m10 + m11")
    e("	adc.w	r2, r11, r11")
    e("	adds	r10, r10, r5			@ + c1 -> r10 is d2")
    e("	adcs	r2, r2, r5, asr #31		@ r2 = c2")

    # Step 3: val3 = m11 + c2
    e("	adds	lr, r12, r2			@ lr is d3")
    e("	adc.w	r4, r11, r11")
    e("	add	r4, r4, r2, asr #31		@ r4 is d4")

    # 2. Chain 1: Sum = Thi + M (using paired vmov and ldrd)
    for k in range(0, 12, 2):
        e(f"	vmov	r6, r7, s{12+k}, s{13+k}	@ Thi[{k}], Thi[{k+1}]")
        e(f"	ldrd	r0, r1, [sp, #{k*4}]		@ m[{k}], m[{k+1}]")
        if k == 0:
            e(f"	adds	r6, r6, r0")
            e(f"	adcs	r7, r7, r1")
        else:
            e(f"	adcs	r6, r6, r0")
            e(f"	adcs	r7, r7, r1")
        e(f"	vmov	s{12+k}, s{13+k}, r6, r7")
    e("	adc.w	r3, r11, r11			@ r3 = sum_carry")

    # 3. Chain 2: Z = Sum - D
    # D is in: r8 (d0), r9 (d1), r10 (d2), lr (d3), r4 (d4)
    e("	vmov	r6, r7, s12, s13")
    e("	subs	r6, r6, r8			@ Sum[0] - d0")
    e("	sbcs	r7, r7, r9			@ Sum[1] - d1")
    e("	vmov	s12, s13, r6, r7")

    e("	vmov	r6, r7, s14, s15")
    e("	sbcs	r6, r6, r10			@ Sum[2] - d2")
    e("	sbcs	r7, r7, lr			@ Sum[3] - d3")
    e("	vmov	s14, s15, r6, r7")

    e("	vmov	r6, r7, s16, s17")
    e("	sbcs	r6, r6, r4			@ Sum[4] - d4")
    e("	sbcs	r7, r7, r11			@ Sum[5] - 0")
    e("	vmov	s16, s17, r6, r7")

    for k in range(6, 12, 2):
        e(f"	vmov	r6, r7, s{12+k}, s{13+k}")
        e(f"	sbcs	r6, r6, r11")
        e(f"	sbcs	r7, r7, r11")
        e(f"	vmov	s{12+k}, s{13+k}, r6, r7")

    e("	sbcs	r3, r3, r11			@ r3 = final_carry")

    # 4. Conditional subtraction Z - p
    e("	mvn	lr, #0				@ 0xffffffff")
    e("	mvn	r12, #1				@ 0xfffffffe")

    # Borrow pass: Z - p
    e("	vmov	r6, r7, s12, s13")
    e("	subs	r6, r6, lr")
    e("	sbcs	r7, r7, r11")

    e("	vmov	r8, r9, s14, s15")
    e("	sbcs	r8, r8, r11")
    e("	sbcs	r9, r9, lr")

    e("	vmov	r8, r9, s16, s17")
    e("	sbcs	r8, r8, r12")
    e("	sbcs	r9, r9, lr")

    e("	vmov	r8, r9, s18, s19")
    e("	sbcs	r8, r8, lr")
    e("	sbcs	r9, r9, lr")

    e("	vmov	r8, r9, s20, s21")
    e("	sbcs	r8, r8, lr")
    e("	sbcs	r9, r9, lr")

    e("	vmov	r8, r9, s22, s23")
    e("	sbcs	r8, r8, lr")
    e("	sbcs	r9, r9, lr")

    e("	sbcs	r3, r3, r11")
    e("	sbc	r10, r10, r10			@ -1 if Z < p, 0 if Z >= p")
    e("	mvn	r10, r10			@ 0 if Z < p, all-ones if Z >= p")

    # Mask p:
    e("	and	r12, r12, r10")
    e("	and	lr, lr, r10")

    # Write to out = Z - (p & mask)
    e("	ldr	r0, [sp, #48]			@ recover `out`")

    e("	vmov	r6, r7, s12, s13")
    e("	subs	r6, r6, lr")
    e("	sbcs	r7, r7, r11")
    e("	strd	r6, r7, [r0, #0]")

    e("	vmov	r6, r7, s14, s15")
    e("	sbcs	r6, r6, r11")
    e("	sbcs	r7, r7, lr")
    e("	strd	r6, r7, [r0, #8]")

    e("	vmov	r6, r7, s16, s17")
    e("	sbcs	r6, r6, r12")
    e("	sbcs	r7, r7, lr")
    e("	strd	r6, r7, [r0, #16]")

    e("	vmov	r6, r7, s18, s19")
    e("	sbcs	r6, r6, lr")
    e("	sbcs	r7, r7, lr")
    e("	strd	r6, r7, [r0, #24]")

    e("	vmov	r6, r7, s20, s21")
    e("	sbcs	r6, r6, lr")
    e("	sbcs	r7, r7, lr")
    e("	strd	r6, r7, [r0, #32]")

    e("	vmov	r6, r7, s22, s23")
    e("	sbcs	r6, r6, lr")
    e("	sbcs	r7, r7, lr")
    e("	strd	r6, r7, [r0, #40]")

    e("	add	sp, sp, #56")
    e("	vpop	{d8-d11}")
    e("	add	sp, sp, #4")
    e("	pop	{r4-r11, pc}")
    e("	.size	nistp_mul_mont_12, .-nistp_mul_mont_12")

    return "\n".join(L)



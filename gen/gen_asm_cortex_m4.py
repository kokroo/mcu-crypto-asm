#!/usr/bin/env python3
"""Emit asm/cortex_m4.S — unrolled CIOS Montgomery multiply using UMAAL.

Generated rather than hand-written: P-256 needs ~120 UMAAL and P-384 ~264.
Hand-maintaining that is how you get a silent carry bug.

The whole routine is built on one instruction:

    UMAAL RdLo, RdHi, Rn, Rm   ->   RdHi:RdLo = Rn*Rm + RdHi + RdLo

which is exactly the CIOS inner step `(C, t[j]) = t[j] + a[j]*b[i] + C`,
single cycle on Cortex-M4, and cannot overflow 64 bits.

n0' == 1 for both NIST primes (p ≡ -1 mod 2^32), so the reduction multiplier
is just `m = t[0]` — no multiply at all. gen_params.py asserts this.

Register map:
    r0 = out   r1 = a    r2 = b (walked)   r3 = p
    r4 = &t    r5 = b[i] then m            r6 = carry C
    r7 = t[j]  r8 = a[j]/p[j]              r9 = i counter
    r10 = select mask
"""
import pathlib

# The modulus is a compile-time constant, and each NIST prime uses only THREE
# distinct limb values. Holding them in registers removes one `ldr` from every
# step of the reduction pass -- n^2 loads per multiply (64 for P-256, 144 for
# P-384).
MODULI = {
    8: 2**256 - 2**224 + 2**192 + 2**96 - 1,
    12: 2**384 - 2**128 - 2**96 + 2**32 - 1,
}


def limbs(x, n):
    return [(x >> (32 * i)) & 0xFFFFFFFF for i in range(n)]


def const_regs(p_limbs):
    """Map each distinct modulus limb value to a register holding it.

    r11 always holds 0 (it is already needed for carry-only adds). The other
    distinct values get r12 and lr, both free here: r12 is caller-saved, and
    lr is dead because the routine returns via `pop {..., pc}`.
    """
    distinct = sorted(set(p_limbs))
    mapping, setup, spare = {}, [], ["r12", "lr"]
    for v in distinct:
        if v == 0:
            mapping[v] = "r11"
            continue
        reg = spare.pop(0)
        mapping[v] = reg
        if v == 0xFFFFFFFF:
            setup.append(f"	mvn	{reg}, #0			@ 0xffffffff")
        elif v == 0xFFFFFFFE:
            setup.append(f"	mvn	{reg}, #1			@ 0xfffffffe")
        elif v < 256:
            setup.append(f"	mov	{reg}, #{v}")
        else:
            setup.append(f"	movw	{reg}, #{v & 0xFFFF}")
            setup.append(f"	movt	{reg}, #{v >> 16}")
    return mapping, setup

HEADER = r"""@ GENERATED by gen/gen_asm_cortex_m4.py -- do not edit.
@
@ Constant-time Montgomery multiplication for the NIST P-256 / P-384 primes.
@ Requires ARMv7-M (Cortex-M3/M4/M7) or ARMv7-A for UMAAL. Thumb-2; included via global_asm!.

	.syntax unified
	.thumb
	.text
"""


def emit_mul(n):
    """Fully-unrolled FIOS Montgomery multiply for `n` limbs.

    CIOS makes two passes over t[] per outer iteration -- one to accumulate
    a*b[i], one to reduce -- so every limb is loaded and stored twice. FIOS
    fuses them: each limb is loaded once, gets both UMAALs, and is stored once.
    Per limb pair that is 3 memory instructions instead of 5, and memory is the
    bottleneck on both cores.

    The cost is a second carry (the multiply and reduction chains can no longer
    share one), which needs a 14th register. The outer loop is therefore fully
    unrolled to free the loop counter, and `out` is parked in the stack frame
    so r0 can serve as the reduction carry.

    Registers:
      r0 = C2 (reduce)   r1 = a      r2 = b      r3 = t hi temp
      r4 = &t            r5 = b[i]   r6 = C1 (multiply)  r7 = t lo temp
      r8 = a lo temp     r9 = m      r10 = a hi temp     r11 = 0
      r12, lr = modulus constants
    """
    assert n % 2 == 0
    L = []
    e = L.append
    TS = ((n + 3) * 4 + 7) & ~7          # t[0..n] plus a slot for `out`
    OUT_SLOT = (n + 2) * 4
    name = f"nistp_mul_mont_{n}"
    pl = limbs(MODULI[n], n)
    creg, csetup = const_regs(pl)

    e("")
    e(f"@ void {name}(uint32_t out[{n}], const uint32_t a[{n}],")
    e(f"@                const uint32_t b[{n}], const uint32_t p[{n}]);")
    e(f"@ out = a * b * R^-1 mod p,  R = 2^{32*n}.  FIOS, fully unrolled.")
    e(f"@ NOTE: the p[] argument is ignored -- the modulus is a compile-time")
    e(f"@ constant held in registers.")
    e(f"	.globl	{name}")
    e(f"	.p2align 2")
    e(f"	.thumb_func")
    e(f"	.type	{name}, %function")
    e(f"{name}:")
    e(f"	push	{{r4-r11, lr}}")
    e(f"	sub	sp, sp, #{TS}")
    e(f"	mov	r4, sp")
    e(f"	str	r0, [r4, #{OUT_SLOT}]	@ park `out`; r0 becomes the reduce carry")
    e(f"	mov	r11, #0			@ permanent zero")
    e(f"	@ modulus limbs in registers: " +
      ", ".join(f"0x{v:08x}->{r}" for v, r in sorted(creg.items())))
    for line in csetup:
        e(line)
    e(f"	@ t = 0")
    for j in range(0, n + 2, 2):
        e(f"	strd	r11, r11, [r4, #{j*4}]")

    for i in range(n):
        e(f"	@ ---- i = {i} ----")
        e(f"	ldr	r5, [r2, #{i*4}]		@ b[{i}]")
        # j = 0: produce S, derive m, start the reduction chain.
        e(f"	ldr	r8, [r1, #0]")
        e(f"	ldr	r7, [r4, #0]")
        e(f"	mov	r6, #0			@ C1 = 0")
        e(f"	umaal	r7, r6, r8, r5		@ S = t[0] + a[0]*b[i]")
        e(f"	mov	r9, r7			@ m = S   (n0' == 1)")
        e(f"	mov	r0, #0			@ C2 = 0")
        e(f"	umaal	r7, r0, r9, {creg[pl[0]]}		@ low word cancels")
        # j = 1 alone (j runs 1..n-1, an odd count), then pairs.
        e(f"	ldr	r8, [r1, #4]")
        e(f"	ldr	r7, [r4, #4]")
        e(f"	umaal	r7, r6, r8, r5")
        e(f"	umaal	r7, r0, r9, {creg[pl[1]]}		@ p[1] = 0x{pl[1]:08x}")
        e(f"	str	r7, [r4, #0]		@ t[0] = S")
        for j in range(2, n, 2):
            e(f"	ldrd	r8, r10, [r1, #{j*4}]")
            e(f"	ldrd	r7, r3, [r4, #{j*4}]")
            e(f"	umaal	r7, r6, r8, r5")
            e(f"	umaal	r3, r6, r10, r5")
            e(f"	umaal	r7, r0, r9, {creg[pl[j]]}")
            e(f"	umaal	r3, r0, r9, {creg[pl[j+1]]}")
            e(f"	strd	r7, r3, [r4, #{(j-1)*4}]")
        # tail: fold both carries into the overflow word.
        e(f"	ldr	r7, [r4, #{n*4}]")
        e(f"	adds	r7, r7, r6")
        e(f"	adc.w	r8, r11, r11")
        e(f"	adds	r7, r7, r0")
        e(f"	adc.w	r10, r11, r11")
        e(f"	str	r7, [r4, #{(n-1)*4}]")
        e(f"	add	r8, r8, r10")
        e(f"	str	r8, [r4, #{n*4}]		@ t[{n}] = carries")

    # ---- conditional subtraction ----
    e(f"	ldr	r0, [r4, #{OUT_SLOT}]	@ recover `out`")
    e(f"	ldr	r7, [r4, #0]")
    e(f"	subs	r7, r7, {creg[pl[0]]}")
    e(f"	str	r7, [r0, #0]")
    for j in range(1, n):
        e(f"	ldr	r7, [r4, #{j*4}]")
        e(f"	sbcs	r7, r7, {creg[pl[j]]}")
        e(f"	str	r7, [r0, #{j*4}]")
    e(f"	ldr	r7, [r4, #{n*4}]")
    e(f"	sbcs	r7, r7, r11")
    e(f"	sbc	r10, r10, r10		@ 0 if no borrow, else all ones")
    for j in range(0, n, 2):
        e(f"	ldrd	r7, r3, [r0, #{j*4}]")
        e(f"	ldrd	r8, r12, [r4, #{j*4}]")
        e(f"	eor	r8, r8, r7")
        e(f"	eor	r12, r12, r3")
        e(f"	and	r8, r8, r10")
        e(f"	and	r12, r12, r10")
        e(f"	eor	r7, r7, r8		@ branchless select")
        e(f"	eor	r3, r3, r12")
        e(f"	strd	r7, r3, [r0, #{j*4}]")

    e(f"	add	sp, sp, #{TS}")
    e(f"	pop	{{r4-r11, pc}}")
    e(f"	.size	{name}, .-{name}")
    return "\n".join(L)


out = [HEADER]
for n in (8, 12):
    out.append(emit_mul(n))
out.append("")

dst = pathlib.Path(__file__).resolve().parent.parent / "asm" / "cortex_m4.S"
dst.parent.mkdir(exist_ok=True)
dst.write_text("\n".join(out))
lines = dst.read_text().count("\n")
umaal = dst.read_text().count("umaal")
print(f"wrote {dst}  ({lines} lines, {umaal} UMAAL)")

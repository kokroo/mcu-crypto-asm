#[test]
fn sha512_224_256_abc() {
    use drv::{Sha512_224, Sha512_256};
    let mut c = <McuCryptoAsmDriver as Sha512_224>::init();
    <McuCryptoAsmDriver as Sha512_224>::update(&mut c, b"abc");
    let mut out = [0u8; 28];
    <McuCryptoAsmDriver as Sha512_224>::finalize(c, &mut out);
    assert_eq!(
        out[..4],
        [0x46, 0x34, 0x27, 0x0f],
        "SHA-512/224(abc) prefix mismatch"
    );

    let mut c = <McuCryptoAsmDriver as Sha512_256>::init();
    <McuCryptoAsmDriver as Sha512_256>::update(&mut c, b"abc");
    let mut out = [0u8; 32];
    <McuCryptoAsmDriver as Sha512_256>::finalize(c, &mut out);
    assert_eq!(
        out[..4],
        [0xdd, 0xaa, 0xf2, 0x5a],
        "SHA-512/256(abc) prefix mismatch"
    );
}

#[test]

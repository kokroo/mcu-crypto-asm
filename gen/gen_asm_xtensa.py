#!/usr/bin/env python3
"""Emit asm/xtensa_lx7.S — CIOS Montgomery multiply for Xtensa LX7.

Xtensa has no UMAAL and, more importantly, **no carry flag at all**. The
Cortex-M4 inner step

    (C, t[j]) = t[j] + a[j]*b[i] + C          -- one UMAAL, 1 cycle

becomes eight instructions here:

    mull   lo, aj, bi          lo = low32(aj*bi)
    muluh  hi, aj, bi          hi = high32(aj*bi)
    add    lo, lo, tj          fold in t[j]
    saltu  c,  lo, tj            carry = (sum < addend)
    add    hi, hi, c
    add    lo, lo, C           fold in the running carry
    saltu  c,  lo, C
    add    hi, hi, c

`SALTU` (set-if-less-than-unsigned) is the branchless carry primitive, used
for both carry-out of an add and borrow-out of a subtract. It is **LX7 only**
— present on ESP32-S2/S3, absent on the original ESP32 (LX6); verified by
assembling this file against the per-core configs shipped with the esp
toolchain. There is deliberately no LX6 variant: the original ESP32 falls
back to the portable backend.

Because Xtensa's windowed ABI makes stack frames fiddly, `t[]` is passed in
by the caller as a scratch pointer rather than allocated here. That keeps the
routine a pure leaf and identical under both the windowed and call0 ABIs
apart from the prologue/epilogue.

Register map (after ENTRY, windowed ABI):
    a2 = out    a3 = a      a4 = b (walked)   a5 = p    a6 = t (scratch)
    a7 = b[i]/m           a8 = carry C        a9 = temp / t[j]
    a10 = a[j]/p[j]       a11 = hi            a12 = carry temp
    a13 = loop counter    a15 = lo
"""
import pathlib
import sys

# The modulus is a compile-time constant. On Xtensa a full CIOS reduction step
# costs ~11 instructions, so limbs that are 0 or 1 are worth special-casing:
# P-256 has three 0 limbs and one 1 limb, P-384 has two 0 limbs.
MODULI = {
    8: 2**256 - 2**224 + 2**192 + 2**96 - 1,
    12: 2**384 - 2**128 - 2**96 + 2**32 - 1,
}


def limbs(x, n):
    return [(x >> (32 * i)) & 0xFFFFFFFF for i in range(n)]

WINDOWED = "--call0" not in sys.argv

HEADER = """# GENERATED by gen/gen_asm_xtensa.py -- do not edit.
#
# Constant-time Montgomery multiplication for the NIST P-256 / P-384 primes,
# Xtensa LX7 (ESP32-S2 / ESP32-S3).
#
# ABI: {abi}.  Requires SALTU (LX7: ESP32-S2 / ESP32-S3).
#
# void nistp_mul_mont_N(uint32_t *out, const uint32_t *a, const uint32_t *b,
#                       const uint32_t *p, uint32_t *scratch /* N+2 words */);

	.text
"""


def carry_into(dst, sum_reg, addend, tmp):
    """Emit `dst += carry_out_of(sum_reg = ... + addend)`.

    An unsigned add overflows iff the sum is less than either addend, so
    SALTU against one addend is exactly the carry bit. Branchless.
    """
    return [
        f"	saltu	{tmp}, {sum_reg}, {addend}",
        f"	add	{dst}, {dst}, {tmp}",
    ]


def const_regs_x(pl):
    """Map the distinct NON-ZERO modulus limbs to registers.

    Zero limbs never need one: those reduction steps skip the product
    entirely. Both NIST primes have exactly two distinct non-zero values, so
    a5 and a14 suffice -- a5 is free because the `p` pointer is no longer used
    anywhere (the conditional subtraction uses the constants too), and a14 was
    only ever a conditional-subtraction temporary.
    """
    distinct = sorted({v for v in pl if v not in (0, 1)})
    assert len(distinct) <= 2, distinct
    regs = ["a5", "a14"]
    mapping, setup = {}, []
    for v, r in zip(distinct, regs):
        mapping[v] = r
        if v == 0xFFFFFFFF:
            setup.append(f"	movi	{r}, -1			# 0xffffffff")
        elif v == 0xFFFFFFFE:
            setup.append(f"	movi	{r}, -2			# 0xfffffffe")
        else:
            setup.append(f"	movi	{r}, {v}")
    return mapping, setup


def emit_mul(n):
    """Fully-unrolled FIOS for `n` limbs.

    Same idea as the Cortex-M4 backend: fuse the multiply and reduction passes
    so each limb of t[] is loaded and stored once instead of twice.

    Xtensa needs care to keep this a win. The running carries must not need a
    `mov` back into place, and FIOS has TWO carry chains, so four registers
    alternate: C1 between a8/a2, C2 between a11/a14. That is one register more
    than exists, so the outer loop is fully unrolled (freeing the counter) and
    the single rare modulus limb (0xfffffffe, once per iteration on P-384) is
    materialised inline with `movi` instead of occupying a register.

    Registers:
      a2/a8 = C1     a3 = a      a4 = b      a5 = 0xffffffff
      a6 = t         a7 = b[i]   a9 = t/const temp   a10 = a/mul temp
      a11/a14 = C2   a12 = carry temp   a13 = m   a15 = S
    """
    L = []
    e = L.append
    name = f"nistp_mul_mont_{n}"
    pl = limbs(MODULI[n], n)
    OUT_SLOT = (n + 2) * 4

    e("")
    e(f"# out = a * b * R^-1 mod p,  R = 2^{32*n}.  FIOS, fully unrolled.")
    e(f"# NOTE: the p argument is ignored; the modulus is a compile-time constant.")
    e(f"	.globl	{name}")
    e(f"	.align	4")
    e(f"	.type	{name}, @function")
    e(f"{name}:")
    if WINDOWED:
        e("	entry	a1, 32			# no stack locals; scratch is an argument")
    else:
        e("	addi	a1, a1, -16		# call0: preserve a12-a15")
        e("	s32i	a12, a1, 0")
        e("	s32i	a13, a1, 4")
        e("	s32i	a14, a1, 8")
        e("	s32i	a15, a1, 12")
    e(f"	s32i	a2, a6, {OUT_SLOT}	# park `out` in the scratch buffer")
    e("	movi	a5, -1			# 0xffffffff")
    e("	movi	a9, 0")
    for j in range(n + 2):
        e(f"	s32i	a9, a6, {j*4}")

    def pconst(j, tmp="a9"):
        """Register holding p[j], materialising it inline when it is rare."""
        if pl[j] == 0xFFFFFFFF:
            return "a5", []
        return tmp, [f"	movi	{tmp}, {pl[j] - (1 << 32)}		# p[{j}] = 0x{pl[j]:08x}"]

    for i in range(n):
        c1, c1n = "a8", "a2"
        c2, c2n = "a11", "a14"
        e(f"	# ---- i = {i} ----")
        e(f"	l32i	a7, a4, {i*4}		# b[{i}]")
        # j = 0: build S, derive m, open the reduction chain.
        e("	l32i	a10, a3, 0")
        e("	l32i	a9, a6, 0")
        e("	mull	a15, a10, a7")
        e(f"	muluh	{c1}, a10, a7")
        e("	add	a15, a15, a9")
        e("	saltu	a12, a15, a9")
        e(f"	add	{c1}, {c1}, a12")
        e("	mov	a13, a15			# m = S  (n0' == 1)")
        reg, pre = pconst(0)
        L.extend(pre)
        e(f"	mull	a10, {reg}, a13")
        e(f"	muluh	{c2}, {reg}, a13")
        e("	add	a15, a15, a10		# low word cancels")
        e("	saltu	a12, a15, a10")
        e(f"	add	{c2}, {c2}, a12")

        for j in range(1, n):
            e(f"	l32i	a10, a3, {j*4}		# a[{j}]")
            e(f"	l32i	a9, a6, {j*4}		# t[{j}]")
            e("	mull	a15, a10, a7")
            e(f"	muluh	{c1n}, a10, a7")
            e("	add	a15, a15, a9")
            e("	saltu	a12, a15, a9")
            e(f"	add	{c1n}, {c1n}, a12")
            e(f"	add	a15, a15, {c1}")
            e(f"	saltu	a12, a15, {c1}")
            e(f"	add	{c1n}, {c1n}, a12")
            if pl[j] == 0:
                e(f"	add	a15, a15, {c2}		# p[{j}] == 0")
                e(f"	saltu	{c2n}, a15, {c2}")
            else:
                reg, pre = pconst(j)
                L.extend(pre)
                e(f"	mull	a10, {reg}, a13")
                e(f"	muluh	{c2n}, {reg}, a13")
                e("	add	a15, a15, a10")
                e("	saltu	a12, a15, a10")
                e(f"	add	{c2n}, {c2n}, a12")
                e(f"	add	a15, a15, {c2}")
                e(f"	saltu	a12, a15, {c2}")
                e(f"	add	{c2n}, {c2n}, a12")
            e(f"	s32i	a15, a6, {(j-1)*4}	# t[{j-1}] = S")
            c1, c1n = c1n, c1
            c2, c2n = c2n, c2

        e(f"	l32i	a9, a6, {n*4}")
        e(f"	add	a15, a9, {c1}")
        e("	saltu	a10, a15, a9")
        e(f"	add	a15, a15, {c2}")
        e(f"	saltu	a12, a15, {c2}")
        e(f"	s32i	a15, a6, {(n-1)*4}")
        e("	add	a10, a10, a12")
        e(f"	s32i	a10, a6, {n*4}		# t[{n}] = carries")

    # ---- conditional subtraction ----
    e(f"	l32i	a2, a6, {OUT_SLOT}	# recover `out`")
    e("	movi	a8, 0			# borrow")
    for j in range(n):
        e(f"	l32i	a9, a6, {j*4}")
        if pl[j] == 0:
            e("	sub	a15, a9, a8")
            e("	saltu	a8, a9, a8")
        else:
            reg, pre = pconst(j, tmp="a10")
            L.extend(pre)
            e(f"	sub	a15, a9, {reg}")
            e(f"	saltu	a12, a9, {reg}")
            e("	sub	a11, a15, a8")
            e("	saltu	a10, a15, a8")
            e("	add	a8, a12, a10")
            e("	mov	a15, a11")
        e(f"	s32i	a15, a2, {j*4}")
    e(f"	l32i	a9, a6, {n*4}")
    e("	saltu	a12, a9, a8")
    e("	neg	a12, a12		# mask")
    for j in range(n):
        e(f"	l32i	a9, a2, {j*4}")
        e(f"	l32i	a10, a6, {j*4}")
        e("	xor	a11, a9, a10")
        e("	and	a11, a11, a12")
        e("	xor	a9, a9, a11		# branchless select")
        e(f"	s32i	a9, a2, {j*4}")

    if WINDOWED:
        e("	retw")
    else:
        e("	l32i	a12, a1, 0")
        e("	l32i	a13, a1, 4")
        e("	l32i	a14, a1, 8")
        e("	l32i	a15, a1, 12")
        e("	addi	a1, a1, 16")
        e("	ret")
    e(f"	.size	{name}, .-{name}")
    return "\n".join(L)


def emit_sqr(n):
    """Constant-time out = a^2 * R^-1 mod p for n limbs using dedicated squaring + Montgomery reduction."""
    L = []
    e = L.append
    name = f"nistp_sqr_mont_{n}"
    pl = limbs(MODULI[n], n)
    OUT_SLOT = (2 * n + 4) * 4

    e("")
    e(f"# out = a^2 * R^-1 mod p,  R = 2^{32*n}.  Dedicated squaring + Montgomery reduction.")
    e(f"	.globl	{name}")
    e(f"	.align	4")
    e(f"	.type	{name}, @function")
    e(f"{name}:")
    if WINDOWED:
        e("	entry	a1, 32")
    else:
        e("	addi	a1, a1, -16")
        e("	s32i	a12, a1, 0")
        e("	s32i	a13, a1, 4")
        e("	s32i	a14, a1, 8")
        e("	s32i	a15, a1, 12")

    e("	mov	a6, a5			# scratch buffer pointer in a6")
    e(f"	s32i	a2, a6, {OUT_SLOT}	# park `out` in scratch")

    # Step 1: Zero out scratch buffer (2*n + 4 words)
    e("	movi	a9, 0")
    for j in range(2 * n + 4):
        e(f"	s32i	a9, a6, {j * 4}")

    # Step 2: Triangular off-diagonal products (i < j)
    e("	# Stage 1: Off-diagonal triangular products")
    for i in range(n - 1):
        e(f"	l32i	a7, a3, {i * 4}		# a[{i}]")
        e("	movi	a8, 0			# carry C = 0")
        for j in range(i + 1, n):
            e(f"	l32i	a10, a3, {j * 4}	# a[{j}]")
            e(f"	l32i	a9, a6, {(i + j) * 4}	# t[{i + j}]")
            e("	mull	a15, a10, a7")
            e("	muluh	a14, a10, a7")
            e("	add	a15, a15, a9")
            e("	saltu	a12, a15, a9")
            e("	add	a14, a14, a12")
            e("	add	a15, a15, a8")
            e("	saltu	a12, a15, a8")
            e("	add	a8, a14, a12		# new carry C")
            e(f"	s32i	a15, a6, {(i + j) * 4}	# t[{i + j}]")
        e(f"	s32i	a8, a6, {(i + n) * 4}	# t[{i + n}] = tail carry")

    # Step 3: Double off-diagonals (shift left 1)
    e("	# Stage 2: Double off-diagonals (shift left 1)")
    e("	movi	a8, 0			# carry = 0")
    for k in range(1, 2 * n):
        e(f"	l32i	a9, a6, {k * 4}")
        e("	srli	a12, a9, 31		# next carry")
        e("	slli	a9, a9, 1")
        e("	or	a9, a9, a8")
        e(f"	s32i	a9, a6, {k * 4}")
        e("	mov	a8, a12")
    e(f"	s32i	a8, a6, {(2 * n) * 4}	# t[{2 * n}] = final carry")

    # Step 4: Add diagonal squares a[i]^2
    e("	# Stage 3: Add diagonal squares a[i]^2")
    for i in range(n):
        e(f"	l32i	a7, a3, {i * 4}		# a[{i}]")
        e("	mull	a15, a7, a7		# lo")
        e("	muluh	a14, a7, a7		# hi")
        e(f"	l32i	a9, a6, {(2 * i) * 4}")
        e("	add	a15, a15, a9")
        e("	saltu	a12, a15, a9")
        e(f"	s32i	a15, a6, {(2 * i) * 4}")

        e(f"	l32i	a9, a6, {(2 * i + 1) * 4}")
        e("	add	a14, a14, a12")
        e("	saltu	a8, a14, a12")
        e("	add	a15, a9, a14")
        e("	saltu	a10, a15, a9")
        e("	add	a8, a8, a10		# carry into t[2*i + 2]")
        e(f"	s32i	a15, a6, {(2 * i + 1) * 4}")

        e(f"	l32i	a9, a6, {(2 * i + 2) * 4}")
        e("	add	a15, a9, a8")
        e("	saltu	a8, a15, a9")
        e(f"	s32i	a15, a6, {(2 * i + 2) * 4}")

        e(f"	l32i	a9, a6, {(2 * i + 3) * 4}")
        e("	add	a15, a9, a8")
        e(f"	s32i	a15, a6, {(2 * i + 3) * 4}")

    # Step 5: Montgomery Reduction
    e("	# Stage 4: Montgomery Reduction")
    e("	movi	a5, -1			# 0xffffffff")

    def pconst_sqr(j, tmp="a10"):
        if pl[j] == 0xFFFFFFFF:
            return "a5", []
        return tmp, [f"	movi	{tmp}, {pl[j] - (1 << 32)}		# p[{j}] = 0x{pl[j]:08x}"]

    for i in range(n):
        e(f"	# ---- reduction row i = {i} ----")
        e(f"	l32i	a7, a6, {i * 4}		# m = t[{i}]")
        e("	mov	a8, a7			# j = 0: low word cancelled, carry is m")
        for j in range(1, n):
            e(f"	l32i	a9, a6, {(i + j) * 4}	# t[{i + j}]")
            pj = pl[j]
            if pj == 0:
                e("	add	a15, a9, a8")
                e("	saltu	a8, a15, a9")
                e(f"	s32i	a15, a6, {(i + j) * 4}")
            elif pj == 0xFFFFFFFF:
                e("	add	a15, a9, a8")
                e("	saltu	a12, a15, a9")
                e("	sub	a11, a15, a7")
                e("	saltu	a14, a15, a7")
                e("	add	a8, a7, a12")
                e("	sub	a8, a8, a14")
                e(f"	s32i	a11, a6, {(i + j) * 4}")
            elif pj == 1:
                e("	add	a15, a9, a7")
                e("	saltu	a12, a15, a9")
                e("	add	a11, a15, a8")
                e("	saltu	a14, a11, a15")
                e("	add	a8, a12, a14")
                e(f"	s32i	a11, a6, {(i + j) * 4}")
            else:
                reg, pre = pconst_sqr(j)
                L.extend(pre)
                e(f"	mull	a15, {reg}, a7")
                e(f"	muluh	a14, {reg}, a7")
                e("	add	a15, a15, a9")
                e("	saltu	a12, a15, a9")
                e("	add	a14, a14, a12")
                e("	add	a15, a15, a8")
                e("	saltu	a12, a15, a8")
                e("	add	a8, a14, a12")
                e(f"	s32i	a15, a6, {(i + j) * 4}")

        # Propagate reduction carry a8 across 3 words:
        k = i + n
        e(f"	l32i	a9, a6, {k * 4}")
        e("	add	a15, a9, a8")
        e("	saltu	a8, a15, a9")
        e(f"	s32i	a15, a6, {k * 4}")

        e(f"	l32i	a9, a6, {(k + 1) * 4}")
        e("	add	a15, a9, a8")
        e("	saltu	a8, a15, a9")
        e(f"	s32i	a15, a6, {(k + 1) * 4}")

        e(f"	l32i	a9, a6, {(k + 2) * 4}")
        e("	add	a15, a9, a8")
        e(f"	s32i	a15, a6, {(k + 2) * 4}")

    # Step 6: Conditional Subtraction
    e(f"	l32i	a2, a6, {OUT_SLOT}	# recover `out`")
    e("	movi	a8, 0			# borrow")
    for j in range(n):
        e(f"	l32i	a9, a6, {(n + j) * 4}")
        if pl[j] == 0:
            e("	sub	a15, a9, a8")
            e("	saltu	a8, a9, a8")
        else:
            reg, pre = pconst_sqr(j, tmp="a10")
            L.extend(pre)
            e(f"	sub	a15, a9, {reg}")
            e(f"	saltu	a12, a9, {reg}")
            e("	sub	a11, a15, a8")
            e("	saltu	a10, a15, a8")
            e("	add	a8, a12, a10")
            e("	mov	a15, a11")
        e(f"	s32i	a15, a2, {j * 4}")
    e(f"	l32i	a9, a6, {(2 * n) * 4}")
    e("	saltu	a12, a9, a8")
    e("	neg	a12, a12		# mask")
    for j in range(n):
        e(f"	l32i	a9, a2, {j * 4}")
        e(f"	l32i	a10, a6, {(n + j) * 4}")
        e("	xor	a11, a9, a10")
        e("	and	a11, a11, a12")
        e("	xor	a9, a9, a11		# branchless select")
        e(f"	s32i	a9, a2, {j * 4}")

    if WINDOWED:
        e("	retw")
    else:
        e("	l32i	a12, a1, 0")
        e("	l32i	a13, a1, 4")
        e("	l32i	a14, a1, 8")
        e("	l32i	a15, a1, 12")
        e("	addi	a1, a1, 16")
        e("	ret")
    e(f"	.size	{name}, .-{name}")
    return "\n".join(L)


def emit_add_mod(n):
    """Constant-time out = (a + b) mod p for n limbs."""
    L = []
    e = L.append
    name = f"nistp_add_mod_{n}"
    pl = limbs(MODULI[n], n)
    stack_size = 112 if n == 8 else 144

    e("")
    e(f"# out = a + b mod p,  N = {n}")
    e(f"	.globl	{name}")
    e(f"	.align	4")
    e(f"	.type	{name}, @function")
    e(f"{name}:")
    if WINDOWED:
        e(f"	entry	a1, {stack_size}")
        BASE = 32
    else:
        e(f"	addi	a1, a1, -{stack_size}")
        e("	s32i	a12, a1, 0")
        e("	s32i	a13, a1, 4")
        e("	s32i	a14, a1, 8")
        e("	s32i	a15, a1, 12")
        BASE = 16

    OUT_SLOT = BASE + 8 * n
    e(f"	s32i	a2, a1, {OUT_SLOT}	# park `out`")

    # 1. s = a + b
    for j in range(n):
        e(f"	l32i	a10, a3, {j*4}		# a[{j}]")
        e(f"	l32i	a7, a4, {j*4}		# b[{j}]")
        if j == 0:
            e("	add	a15, a10, a7")
            e("	saltu	a8, a15, a10		# carry")
        else:
            e("	add	a15, a10, a7")
            e("	saltu	a12, a15, a10")
            e("	add	a15, a15, a8")
            e("	saltu	a8, a15, a8")
            e("	add	a8, a8, a12")
        e(f"	s32i	a15, a1, {BASE + j*4}		# s[{j}]")
    e("	mov	a14, a8			# c_out in a14")

    # 2. d = s - p
    e("	movi	a5, -1			# 0xffffffff")
    e("	movi	a6, 1			# 1")
    if n == 12:
        e("	movi	a13, -2			# 0xfffffffe")

    for j in range(n):
        e(f"	l32i	a9, a1, {BASE + j*4}		# s[{j}]")
        pj = pl[j]
        if pj == 0xFFFFFFFF:
            preg = "a5"
        elif pj == 1:
            preg = "a6"
        elif pj == 0xFFFFFFFE and n == 12:
            preg = "a13"
        elif pj == 0:
            preg = None
        else:
            e(f"	movi	a7, {pj - (1<<32)}")
            preg = "a7"

        if j == 0:
            e(f"	sub	a15, a9, {preg}")
            e(f"	saltu	a8, a9, {preg}		# borrow")
        else:
            if preg is None:
                e("	sub	a11, a9, a8")
                e("	saltu	a8, a9, a8")
                e("	mov	a15, a11")
            else:
                e(f"	sub	a15, a9, {preg}")
                e(f"	saltu	a12, a9, {preg}")
                e("	sub	a11, a15, a8")
                e("	saltu	a10, a15, a8")
                e("	add	a8, a12, a10")
                e("	mov	a15, a11")
        DIFF_SLOT = BASE + 4 * n + j * 4
        e(f"	s32i	a15, a1, {DIFF_SLOT}		# d[{j}]")

    # underflow = (c_out < b_out)
    e("	saltu	a12, a14, a8		# underflow = (c_out < b_out)")
    e("	neg	a12, a12		# mask: 0xffffffff if s < p, 0 if s >= p")

    # 3. branchless select: out[j] = d[j] ^ ((d[j] ^ s[j]) & mask)
    e(f"	l32i	a2, a1, {OUT_SLOT}	# recover `out`")
    for j in range(n):
        DIFF_SLOT = BASE + 4 * n + j * 4
        e(f"	l32i	a15, a1, {DIFF_SLOT}	# d[{j}]")
        e(f"	l32i	a9, a1, {BASE + j*4}		# s[{j}]")
        e("	xor	a10, a15, a9")
        e("	and	a10, a10, a12")
        e("	xor	a15, a15, a10")
        e(f"	s32i	a15, a2, {j*4}")

    if WINDOWED:
        e("	retw")
    else:
        e("	l32i	a12, a1, 0")
        e("	l32i	a13, a1, 4")
        e("	l32i	a14, a1, 8")
        e("	l32i	a15, a1, 12")
        e(f"	addi	a1, a1, {stack_size}")
        e("	ret")
    e(f"	.size	{name}, .-{name}")
    return "\n".join(L)


def emit_sub_mod(n):
    """Constant-time out = (a - b) mod p for n limbs."""
    L = []
    e = L.append
    name = f"nistp_sub_mod_{n}"
    pl = limbs(MODULI[n], n)
    stack_size = 80 if n == 8 else 96

    e("")
    e(f"# out = a - b mod p,  N = {n}")
    e(f"	.globl	{name}")
    e(f"	.align	4")
    e(f"	.type	{name}, @function")
    e(f"{name}:")
    if WINDOWED:
        e(f"	entry	a1, {stack_size}")
        BASE = 32
    else:
        e(f"	addi	a1, a1, -{stack_size}")
        e("	s32i	a12, a1, 0")
        e("	s32i	a13, a1, 4")
        e("	s32i	a14, a1, 8")
        e("	s32i	a15, a1, 12")
        BASE = 16

    OUT_SLOT = BASE + 4 * n
    e(f"	s32i	a2, a1, {OUT_SLOT}	# park `out`")

    # 1. d = a - b
    for j in range(n):
        e(f"	l32i	a10, a3, {j*4}		# a[{j}]")
        e(f"	l32i	a7, a4, {j*4}		# b[{j}]")
        if j == 0:
            e("	sub	a15, a10, a7")
            e("	saltu	a8, a10, a7		# borrow")
        else:
            e("	sub	a15, a10, a7")
            e("	saltu	a12, a10, a7")
            e("	sub	a11, a15, a8")
            e("	saltu	a10, a15, a8")
            e("	add	a8, a12, a10")
            e("	mov	a15, a11")
        e(f"	s32i	a15, a1, {BASE + j*4}		# d[{j}]")

    e("	neg	a12, a8			# mask: 0xffffffff if a < b, 0 if a >= b")

    # 2. out = d + (p & mask)
    e("	movi	a5, -1			# 0xffffffff")
    e("	movi	a6, 1			# 1")
    if n == 12:
        e("	movi	a13, -2			# 0xfffffffe")

    e(f"	l32i	a2, a1, {OUT_SLOT}	# recover `out`")
    for j in range(n):
        e(f"	l32i	a15, a1, {BASE + j*4}		# d[{j}]")
        pj = pl[j]
        if pj == 0xFFFFFFFF:
            preg = "a5"
        elif pj == 1:
            preg = "a6"
        elif pj == 0xFFFFFFFE and n == 12:
            preg = "a13"
        elif pj == 0:
            preg = None
        else:
            e(f"	movi	a7, {pj - (1<<32)}")
            preg = "a7"

        if preg is None:
            if j == 0:
                pass
            else:
                e("	add	a15, a15, a8")
                e("	saltu	a8, a15, a8")
        else:
            e(f"	and	a7, {preg}, a12		# p[{j}] & mask")
            if j == 0:
                e("	add	a15, a15, a7")
                e("	saltu	a8, a15, a7		# carry")
            else:
                e("	add	a15, a15, a7")
                e("	saltu	a10, a15, a7")
                e("	add	a15, a15, a8")
                e("	saltu	a8, a15, a8")
                e("	add	a8, a8, a10")
        e(f"	s32i	a15, a2, {j*4}")

    if WINDOWED:
        e("	retw")
    else:
        e("	l32i	a12, a1, 0")
        e("	l32i	a13, a1, 4")
        e("	l32i	a14, a1, 8")
        e("	l32i	a15, a1, 12")
        e(f"	addi	a1, a1, {stack_size}")
        e("	ret")
    e(f"	.size	{name}, .-{name}")
    return "\n".join(L)



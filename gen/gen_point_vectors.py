#!/usr/bin/env python3
"""Emit tests/point_vectors.rs — scalar-multiplication vectors from an
independent affine implementation.

The point layer uses projective Renes-Costello-Batina complete formulas, which
are easy to transcribe subtly wrong. This oracle is deliberately written the
other way: plain affine arithmetic with explicit special cases, so a
transcription error in the projective code cannot be mirrored here.

Includes k = 1, 2, 3 (small doublings/additions), k = n-1 (which is -G, the
inverse case), k = n (which is the identity, the exceptional case complete
formulas exist to handle), and random scalars.
"""
import pathlib

CURVES = {
    "P256": dict(
        n=8,
        p=2**256 - 2**224 + 2**192 + 2**96 - 1,
        order=0xFFFFFFFF00000000FFFFFFFFFFFFFFFFBCE6FAADA7179E84F3B9CAC2FC632551,
        gx=0x6B17D1F2E12C4247F8BCE6E563A440F277037D812DEB33A0F4A13945D898C296,
        gy=0x4FE342E2FE1A7F9B8EE7EB4A7C0F9E162BCE33576B315ECECBB6406837BF51F5,
    ),
    "P384": dict(
        n=12,
        p=2**384 - 2**128 - 2**96 + 2**32 - 1,
        order=0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFC7634D81F4372DDF581A0DB248B0A77AECEC196ACCC52973,
        gx=0xAA87CA22BE8B05378EB1C71EF320AD746E1D3B628BA79B9859F741E082542A385502F25DBF55296C3A545E3872760AB7,
        gy=0x3617DE4A96262C6F5D9E98BF9292DC29F8F41DBD289A147CE9DA3113B5F0B8C00A60B1CE1D7E819D7A431D7C90EA0E5F,
    ),
}


def add(P, Q, p):
    """Affine addition on y^2 = x^3 - 3x + b. None is the identity."""
    a = -3 % p
    if P is None:
        return Q
    if Q is None:
        return P
    x1, y1 = P
    x2, y2 = Q
    if x1 == x2 and (y1 + y2) % p == 0:
        return None
    if P == Q:
        lam = (3 * x1 * x1 + a) * pow(2 * y1, -1, p) % p
    else:
        lam = (y2 - y1) * pow(x2 - x1, -1, p) % p
    x3 = (lam * lam - x1 - x2) % p
    y3 = (lam * (x1 - x3) - y1) % p
    return (x3, y3)


def mul(k, P, p):
    R = None
    for bit in bin(k)[2:] if k else "0":
        R = add(R, R, p)
        if bit == "1":
            R = add(R, P, p)
    return R


def limbs(x, n):
    return [(x >> (32 * i)) & 0xFFFFFFFF for i in range(n)]


def arr(x, n):
    return "[" + ", ".join(f"0x{v:08x}" for v in limbs(x, n)) + "]"


out = [
    "//! GENERATED by `gen/gen_point_vectors.py` — do not edit.",
    "//!",
    "//! `(k, x, y, is_identity)` for `k * G`, computed by an independent affine",
    "//! implementation. All values are plain integers in little-endian limbs.",
    "#![allow(clippy::unreadable_literal)]",
    "",
]

for name, c in CURVES.items():
    n, p, order = c["n"], c["p"], c["order"]
    G = (c["gx"], c["gy"])

    ks = [1, 2, 3, 4, 5, 7, 15, 16, order - 1, order]
    st = 0x9E3779B97F4A7C15
    for _ in range(10):
        acc = 0
        for _ in range(n):
            st = (st * 6364136223846793005 + 1442695040888963407) % (1 << 64)
            acc = (acc << 32) | (st >> 32)
        ks.append(acc % order)

    rows = []
    for k in ks:
        R = mul(k, G, p)
        if R is None:
            rows.append(f"    ({arr(k,n)}, {arr(0,n)}, {arr(0,n)}, true),")
        else:
            rows.append(f"    ({arr(k,n)}, {arr(R[0],n)}, {arr(R[1],n)}, false),")

    out.append(f"/// {name}: (k, x, y, is_identity) for k*G")
    out.append(
        f"pub const {name}_MUL_G: [([u32; {n}], [u32; {n}], [u32; {n}], bool); {len(ks)}] = ["
    )
    out.extend(rows)
    out.append("];")
    out.append("")

dst = pathlib.Path(__file__).resolve().parent.parent / "tests" / "point_vectors.rs"
dst.write_text("\n".join(out))
print(f"wrote {dst}")
for name, c in CURVES.items():
    print(f"  {name}: 20 scalars incl. 1,2,3, n-1 (=-G) and n (=identity)")

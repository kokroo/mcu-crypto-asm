#!/usr/bin/env python3
"""Emit src/params.rs. Constants are derived, never transcribed by hand."""

CURVES = {
    "P256": dict(
        n=8,
        p=2**256 - 2**224 + 2**192 + 2**96 - 1,
        # y^2 = x^3 + a*x + b
        a=-3,
        b=0x5AC635D8AA3A93E7B3EBBD55769886BC651D06B0CC53B0F63BCE3C3E27D2604B,
        order=0xFFFFFFFF00000000FFFFFFFFFFFFFFFFBCE6FAADA7179E84F3B9CAC2FC632551,
        gx=0x6B17D1F2E12C4247F8BCE6E563A440F277037D812DEB33A0F4A13945D898C296,
        gy=0x4FE342E2FE1A7F9B8EE7EB4A7C0F9E162BCE33576B315ECECBB6406837BF51F5,
    ),
    "P384": dict(
        n=12,
        p=2**384 - 2**128 - 2**96 + 2**32 - 1,
        a=-3,
        b=0xB3312FA7E23EE7E4988E056BE3F82D19181D9C6EFE8141120314088F5013875AC656398D8A2ED19D2A85C8EDD3EC2AEF,
        order=0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFC7634D81F4372DDF581A0DB248B0A77AECEC196ACCC52973,
        gx=0xAA87CA22BE8B05378EB1C71EF320AD746E1D3B628BA79B9859F741E082542A385502F25DBF55296C3A545E3872760AB7,
        gy=0x3617DE4A96262C6F5D9E98BF9292DC29F8F41DBD289A147CE9DA3113B5F0B8C00A60B1CE1D7E819D7A431D7C90EA0E5F,
    ),
}


def limbs(x, n):
    """Little-endian 32-bit limbs."""
    return [(x >> (32 * i)) & 0xFFFFFFFF for i in range(n)]


def fmt(name, x, n, doc):
    ls = limbs(x, n)
    body = ",\n    ".join(
        ", ".join(f"0x{v:08x}" for v in ls[i : i + 4]) for i in range(0, n, 4)
    )
    return f"    /// {doc}\n    pub const {name}: [u32; {n}] = [\n    {body}\n    ];\n"


out = [
    "//! Curve constants. GENERATED by `gen/gen_params.py` — do not edit.",
    "//!",
    "//! Field elements marked `_MONT` are in Montgomery form (multiplied by",
    "//! R = 2^(32*N) mod p). Everything else is a plain integer.",
    "#![allow(clippy::unreadable_literal)]",
    "",
]

for cname, c in CURVES.items():
    n, p = c["n"], c["p"]
    R = (1 << (32 * n)) % p
    R2 = (R * R) % p
    R3 = (R2 * R) % p
    a_mont = (c["a"] % p) * R % p
    b_mont = c["b"] * R % p
    gx_mont = c["gx"] * R % p
    gy_mont = c["gy"] * R % p
    one_mont = R

    # n0inv = -p^-1 mod 2^32. Assert the claim the asm backends rely on.
    n0inv = (-pow(p, -1, 1 << 32)) % (1 << 32)
    assert n0inv == 1, f"{cname}: n0inv is {n0inv}, asm assumes 1"
    assert p % (1 << 32) == 0xFFFFFFFF

    # Scalar field (modulo order) constants
    order = c["order"]
    order_n0inv = (-pow(order, -1, 1 << 32)) % (1 << 32)
    order_r = (1 << (32 * n)) % order
    order_r2 = (order_r * order_r) % order

    out.append(f"/// {cname} ({32*n}-bit prime field).")
    out.append(f"pub mod {cname.lower()} {{")
    out.append(f"    /// Number of 32-bit limbs.")
    out.append(f"    pub const N: usize = {n};")
    out.append(f"    /// -p^-1 mod 2^32. Exactly 1 for this prime; asm relies on it.")
    out.append(f"    pub const N0INV: u32 = {n0inv};")
    out.append(f"    /// -order^-1 mod 2^32. Used for scalar field Montgomery reduction.")
    out.append(f"    pub const ORDER_N0INV: u32 = 0x{order_n0inv:08x};")
    out.append("")
    out.append(fmt("P", p, n, "Field modulus p."))
    out.append(fmt("ORDER", c["order"], n, "Order of the base point."))
    out.append(fmt("ORDER_R_MONT", order_r, n, "R mod order == 1 in Montgomery form for scalar field."))
    out.append(fmt("ORDER_R2_MONT", order_r2, n, "R^2 mod order. Converts scalars into Montgomery form."))
    out.append(fmt("R_MONT", one_mont, n, "R mod p == 1 in Montgomery form."))
    out.append(fmt("R2_MONT", R2, n, "R^2 mod p. Converts into Montgomery form."))
    out.append(fmt("R3_MONT", R3, n, "R^3 mod p. Used by Montgomery inversion."))
    out.append(fmt("A_MONT", a_mont, n, "Curve coefficient a = -3, Montgomery form."))
    out.append(fmt("B_MONT", b_mont, n, "Curve coefficient b, Montgomery form."))
    out.append(fmt("GX_MONT", gx_mont, n, "Base point x, Montgomery form."))
    out.append(fmt("GY_MONT", gy_mont, n, "Base point y, Montgomery form."))
    out.append("}")
    out.append("")

import pathlib

dst = pathlib.Path(__file__).resolve().parent.parent / "src" / "params.rs"
dst.write_text("\n".join(out))
print(f"wrote {dst}")
for cname, c in CURVES.items():
    print(f"  {cname}: n={c['n']} n0inv=1 verified")
